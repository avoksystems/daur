// Builds verifier/index.html (single file, inline CSS and JS, no external requests) and
// dist/core.mjs (the same verification core as an ES module for Node tests).

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..");

// The trust list to bundle: ../trust (the test list) unless DAUR_TRUST_DIR names another trust
// directory, which is how a release build carries the pilot list (docs/key-ceremony.md).
const trustDir = process.env.DAUR_TRUST_DIR || join(repo, "trust");
const schema = readFileSync(join(repo, "src", "daur", "data", "daur-v0.2.schema.json"), "utf8");
const pem = readFileSync(join(trustDir, "avok-pilot-roots.pem"), "utf8");
const manifestText = readFileSync(join(trustDir, "avok-pilot-trust-manifest.json"), "utf8");
const manifest = JSON.parse(manifestText);

writeFileSync(join(here, "src", "schema.generated.js"), `// generated by build.mjs; do not edit\nexport default ${JSON.stringify(JSON.parse(schema))};\n`);
const reserved = readFileSync(join(repo, "src", "daur", "data", "reserved-lists.json"), "utf8");
writeFileSync(join(here, "src", "reserved-lists.generated.js"), `// generated by build.mjs from src/daur/data/reserved-lists.json; do not edit\nexport default ${JSON.stringify(JSON.parse(reserved))};\n`);
const manifestSchema = readFileSync(join(repo, "src", "daur", "data", "trust-manifest-v0.2.schema.json"), "utf8");
writeFileSync(join(here, "src", "manifest-schema.generated.js"), `// generated by build.mjs from src/daur/data/trust-manifest-v0.2.schema.json; do not edit\nexport default ${JSON.stringify(JSON.parse(manifestSchema))};\n`);
const resultCodes = readFileSync(join(repo, "spec", "result-codes.json"), "utf8");
writeFileSync(join(here, "src", "result-codes.generated.js"), `// generated by build.mjs from spec/result-codes.json; do not edit\nexport default ${JSON.stringify(JSON.parse(resultCodes))};\n`);
writeFileSync(
  join(here, "src", "trust-bundle.generated.js"),
  `// generated by build.mjs from trust/; do not edit\nexport default ${JSON.stringify({ pem, manifest, id: manifest.trust_list_id, version: manifest.trust_list_version, issued: manifest.issued })};\n`,
);

mkdirSync(join(here, "dist"), { recursive: true });

await build({
  entryPoints: [join(here, "src", "verify.js")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: ["es2022"],
  mainFields: ["module", "main"],
  outfile: join(here, "dist", "core.mjs"),
  logLevel: "warning",
});

const ui = await build({
  entryPoints: [join(here, "src", "ui.js")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  mainFields: ["browser", "module", "main"],
  minify: true,
  // The notices are carried whole in the page's third-party notices section, generated below.
  legalComments: "none",
  metafile: true,
  write: false,
  logLevel: "warning",
});
const js = ui.outputFiles[0].text;

// Third-party notices (review V3 L7): for every package bundled into the page, its name, version,
// licence and the complete text of its licence file, read at build time.
function escapeHtml(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
const bundled = new Set();
for (const input of Object.keys(ui.metafile.inputs)) {
  const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (m) bundled.add(m[1]);
}
const notices = [...bundled].sort().map((name) => {
  const dir = join(here, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i.test(f)).sort();
  if (!files.length) throw new Error(`${name} ships no licence file; add its notice by hand before bundling it`);
  const texts = files.map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim());
  return `${name} ${pkg.version} (${pkg.license})\n\n${texts.join("\n\n")}`;
});
const noticesHtml = escapeHtml(notices.join("\n\n" + "-".repeat(72) + "\n\n"));
// The page header shows VERIFIER_VERSION from src/verify.js, the constant the core reports in its
// results, so the two cannot drift apart.
const versionMatch = /export const VERIFIER_VERSION = "([^"]+)";/.exec(readFileSync(join(here, "src", "verify.js"), "utf8"));
if (!versionMatch) throw new Error("VERIFIER_VERSION not found in src/verify.js");
const verifierVersion = versionMatch[1];
const css = readFileSync(join(here, "src", "style.css"), "utf8");
const template = readFileSync(join(here, "src", "index.template.html"), "utf8");
const html = template
  .replace("/*__CSS__*/", () => css)
  .replace("/*__JS__*/", () => js.replace(/<\/script/gi, "<\\/script"))
  .replace("__TRUST_VERSION__", `${manifest.trust_list_id} ${manifest.trust_list_version}`)
  .replace("__VERIFIER_VERSION__", verifierVersion)
  .replace("__BUILD_HASH__", createHash("sha256").update(js).digest("hex").slice(0, 12))
  .replace("__THIRD_PARTY_COUNT__", String(notices.length))
  .replace("__THIRD_PARTY_NOTICES__", () => noticesHtml);
writeFileSync(join(here, "index.html"), html);
console.log(`built index.html (${(html.length / 1024).toFixed(0)} KiB) and dist/core.mjs; trust list ${manifest.trust_list_id} ${manifest.trust_list_version} from ${trustDir}`);
console.log(`sha256 of index.html: ${createHash("sha256").update(html).digest("hex")}`);
